for (const lang of LANGS) Object.assign(STRINGS[lang], BOT_STRINGS[lang]);

/** Explicit choice wins; "auto" (or anything unrecognised) follows the browser. */
export function resolveLang(setting, uiLanguage) {
  if (LANGS.includes(setting)) return setting;
  const prefix = String(uiLanguage ?? "").slice(0, 2).toLowerCase();
  return LANGS.includes(prefix) ? prefix : "en";
}

export function t(lang, key, vars) {
  const table = STRINGS[lang] ?? STRINGS.en;
  const template = table[key] ?? STRINGS.en[key];
  if (template === undefined) return key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}
